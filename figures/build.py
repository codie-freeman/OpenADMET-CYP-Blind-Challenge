#!/usr/bin/env python
"""Render every figure to every target.

    python figures/build.py              # all figures, all targets
    python figures/build.py --figure model_comparison_cld
    python figures/build.py --target thesis

Output goes to ``build/<target>/<slug>.<ext>``, which is gitignored. Nothing under
``outputs/``, ``notebooks/``, ``src/``, ``scripts/`` or ``docs/`` is touched.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# Invoked by path rather than as a module, so make the repo importable.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from figures import (                                             # noqa: E402
    spread_ratio_by_submission,
    residual_vs_similarity,
    partition_ordering_agreement,
    label_vs_solved_population,
    error_correlation_matrix,
    cluster_size_distributions,
    chemical_space,
    data_inventory,
    deadzone_decomposition,
    interval_width_vs_potency,
    pairwise_significance,
    rho_proxy_bias,
    cv_board_parity,
    cv_board_rank,
    error_vs_prediction_correlation,
    fold_spread,
    fold_label_distributions,
    hard_compound_similarity,
    hard_compound_structures,
    half_vs_full_set, spread_ratio_by_submission,
    leaderboard_trajectory,
    metric_heatmap,
    observed_vs_predicted,
    mean_range_by_isoform,
    model_comparison_cld,
    probe_branches,
    strae_vs_r2,
)
from figures.style.base import TARGETS, repo_root                 # noqa: E402

FIGURES = [
    # the data
    data_inventory, chemical_space, interval_width_vs_potency,
    label_vs_solved_population, cluster_size_distributions,
    # board record
    leaderboard_trajectory, metric_heatmap, strae_vs_r2,
    half_vs_full_set, spread_ratio_by_submission,
    # identification
    mean_range_by_isoform, probe_branches, rho_proxy_bias,
    # cross-validation against the board
    cv_board_parity, cv_board_rank,
    # cross-validation
    model_comparison_cld, pairwise_significance, fold_spread,
    partition_ordering_agreement, error_correlation_matrix,
    deadzone_decomposition, error_vs_prediction_correlation,
    # chemistry and predictions
    observed_vs_predicted, hard_compound_structures,
    residual_vs_similarity,
    # diagnostics and appendix
    hard_compound_similarity, fold_label_distributions,
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--figure", action="append", choices=[m.SLUG for m in FIGURES],
                        help="render only this figure (repeatable)")
    parser.add_argument("--target", action="append", choices=list(TARGETS),
                        help="render only this target (repeatable)")
    args = parser.parse_args()

    figures = [m for m in FIGURES if not args.figure or m.SLUG in args.figure]
    targets = [TARGETS[n] for n in (args.target or TARGETS)]

    root = repo_root()
    written: list[Path] = []
    failed = 0
    captions: list[tuple[str, str]] = []

    for module in figures:
        for target in targets:
            label = f"{module.SLUG:24} {target.name:7}"
            try:
                path = module.render(target)
            except Exception as exc:                      # keep going; report at the end
                failed += 1
                print(f"{label} -> FAILED: {type(exc).__name__}: {exc}")
                continue
            w, h = module.SIZES[target.name]
            written.append(path)
            if target is targets[0] and getattr(module, "CAPTION", None):
                captions.append((module.SLUG, module.CAPTION.strip()))
            print(f"{label} -> {module.variant(target):34} "
                  f"{w} x {h} in  {path.relative_to(root)}")

    if captions:
        out = root / "build" / "captions.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(
            "# Figure captions\n\nGenerated by `figures/build.py` from each module's `CAPTION`.\n"
            "Everything here was moved out of the figures themselves: in-axes text labels a *part*\n"
            "of a figure, caption text explains it.\n\n"
            + "\n\n".join(f"## `{slug}`\n\n{text}" for slug, text in captions) + "\n")
        print(f"captions -> {out.relative_to(root)} ({len(captions)} figures)")

    print(f"\n{len(written)} file(s) written to {(root / 'build').relative_to(root)}/"
          + (f", {failed} failed" if failed else ""))
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
